#!/usr/bin/env node
// After `next build` and the prune: security headers for the static host,
// written into out/_headers ahead of its cache rules (public/_headers).
//
// - A strict Content-Security-Policy. The only scripts that run are the site's
//   own files and the inline <script>s Next writes into the HTML, each allowed
//   by its sha256 (they change with every build, hence a build step). No eval
//   anywhere: workers load HiGHS with importScripts, zod runs jitless.
// - nosniff, no framing, a strict referrer, cross-origin isolation of the
//   window and resources, and a Permissions-Policy that turns off what the
//   planner never uses.
//
// With NEXT_PUBLIC_ICON_BASE_URL set, that origin may serve images and be
// fetched (icons and their export). With NEXT_PUBLIC_TURNSTILE_SITE_KEY set,
// Turnstile's origin may serve a script and a frame (the request form's bot
// check) and nothing else. Cloudflare refuses header lines over
// 2,000 characters, so the build fails before deploying one.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const outDir = path.resolve(process.argv[2] ?? "out");
const MAX_HEADER_LINE = 2000;

function* htmlFiles(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (full === path.join(outDir, "datasets")) continue;
      yield* htmlFiles(full);
    } else if (entry.name.endsWith(".html")) {
      yield full;
    }
  }
}

const hashes = new Set();
for (const file of htmlFiles(outDir)) {
  const html = fs.readFileSync(file, "utf8");
  for (const match of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/g)) {
    const attrs = match[1] ?? "";
    if (/\bsrc\s*=/.test(attrs)) continue;
    const type = /\btype\s*=\s*"([^"]*)"/.exec(attrs)?.[1];
    // Data blocks (JSON-LD, Next's flight data with a non-JS type) never run.
    if (type && !/^(text\/javascript|module)$/i.test(type)) continue;
    if (!match[2]) continue;
    hashes.add(`'sha256-${crypto.createHash("sha256").update(match[2], "utf8").digest("base64")}'`);
  }
}

const iconOrigin = (() => {
  const base = process.env.NEXT_PUBLIC_ICON_BASE_URL?.trim();
  if (!base) return [];
  try {
    return [new URL(base).origin];
  } catch {
    throw new Error(`NEXT_PUBLIC_ICON_BASE_URL is not a URL: ${base}`);
  }
})();

// With NEXT_PUBLIC_TURNSTILE_SITE_KEY set, the build shows the request form,
// whose bot check is Cloudflare Turnstile: its script and its challenge
// iframe come from this one origin, and that is all it needs (Cloudflare's
// Turnstile CSP reference; its connect-src 'self' is already here). Without a
// key there is no form, so the policy names no third party at all.
const TURNSTILE_ORIGIN = "https://challenges.cloudflare.com";
const turnstile = process.env.NEXT_PUBLIC_TURNSTILE_SITE_KEY?.trim() ? [TURNSTILE_ORIGIN] : [];

const directive = (name, values) => `${name} ${values.join(" ")}`;
const csp = [
  directive("default-src", ["'none'"]),
  directive("script-src", ["'self'", "'wasm-unsafe-eval'", ...turnstile, ...[...hashes].sort()]),
  directive("style-src", ["'self'"]),
  directive("style-src-attr", ["'unsafe-inline'"]),
  directive("img-src", ["'self'", "data:", "blob:", ...iconOrigin]),
  directive("font-src", ["'self'"]),
  directive("connect-src", ["'self'", ...iconOrigin]),
  ...(turnstile.length ? [directive("frame-src", turnstile)] : []),
  directive("worker-src", ["'self'"]),
  directive("manifest-src", ["'self'"]),
  directive("media-src", ["'self'"]),
  directive("object-src", ["'none'"]),
  directive("base-uri", ["'self'"]),
  directive("form-action", ["'none'"]),
  directive("frame-ancestors", ["'none'"]),
].join("; ");

const permissions = [
  "accelerometer=()",
  "autoplay=()",
  "camera=()",
  "display-capture=()",
  "encrypted-media=()",
  "fullscreen=(self)",
  "geolocation=()",
  "gyroscope=()",
  "hid=()",
  "idle-detection=()",
  "magnetometer=()",
  "microphone=()",
  "midi=()",
  "payment=()",
  "publickey-credentials-get=()",
  "screen-wake-lock=()",
  "serial=()",
  "usb=()",
  "xr-spatial-tracking=()",
  "clipboard-read=()",
  "clipboard-write=(self)",
  "browsing-topics=()",
].join(", ");

const block = `# Generated by tools/security-headers.mjs at build time (inline script hashes change every build).
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  Permissions-Policy: ${permissions}

`;

const headersFile = path.join(outDir, "_headers");
// Idempotent: a block from an earlier run is replaced, the cache rules kept.
const existing = fs.existsSync(headersFile)
  ? fs.readFileSync(headersFile, "utf8").replace(/^# Generated by tools\/security-headers\.mjs[\s\S]*?\n\n(?=# )/, "")
  : "";
const text = block + existing;

const tooLong = text.split("\n").filter((line) => line.length > MAX_HEADER_LINE);
if (tooLong.length > 0) {
  console.error(
    `A header line is ${Math.max(...tooLong.map((line) => line.length))} characters; Cloudflare allows ${MAX_HEADER_LINE}. ${hashes.size} inline script hashes.`,
  );
  process.exit(1);
}
fs.writeFileSync(headersFile, text);
console.log(
  `Security headers: ${hashes.size} inline script hashes, longest line ${Math.max(...text.split("\n").map((line) => line.length))} characters.`,
);
